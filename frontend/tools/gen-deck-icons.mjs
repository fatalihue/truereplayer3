// Writes ../Source/DeckIcons.g.cs: the lucide icons the Deck's native window draws on its own (branch
// deck; plan .claude/planos/deck-2026-11-19.md) — the default of each action kind and of each TR3
// command, the missing macro's warning, the folder's Back. A button whose icon the user chose carries its
// own SVG in deck.json, written by the page in the same shape (deckIconSvg, Fase 5). The window draws an
// SVG through Direct2D with "currentColor" swapped for the theme's ink. Run after changing the list
// below or upgrading lucide:
//   node tools/gen-deck-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const front = path.join(here, '..');
const iconsDir = path.join(front, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const out = path.join(front, '..', 'Source', 'DeckIcons.g.cs');

const NAMES = [
  // An action's default (DeckRenderer.DefaultIcon), and a media or volume key's (Fase 5).
  'play', 'keyboard', 'type', 'external-link', 'folder', 'plus',
  'skip-forward', 'skip-back', 'volume-2', 'volume-1', 'volume-x',
  // A TR3 command's.
  'circle', 'square', 'mouse-pointer-click', 'arrow-right-left', 'zap', 'command', 'app-window',
  // The states and the window's own.
  'triangle-alert', 'chevron-left', 'image', 'layout-grid', 'pencil',
];

const version = JSON.parse(fs.readFileSync(path.join(front, 'node_modules', 'lucide-react', 'package.json'), 'utf8')).version;
const attrs = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');

let cs = `// GENERATED by frontend/tools/gen-deck-icons.mjs from lucide-react ${version} (ISC) — do not edit.
namespace TrueReplayer.Services
{
    /// <summary>The lucide icons the Deck's window draws on its own, as SVG with stroke="currentColor".</summary>
    internal static class DeckIcons
    {
        public static readonly System.Collections.Generic.IReadOnlyDictionary<string, string> Svg =
            new System.Collections.Generic.Dictionary<string, string>(System.StringComparer.Ordinal)
            {
`;
for (const name of NAMES) {
  const mod = await import(pathToFileURL(path.join(iconsDir, `${name}.js`)).href);
  const body = mod.__iconNode.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  cs += `                ["${name}"] = ${JSON.stringify(svg)},\n`;
}
cs += `            };
    }
}
`;
fs.writeFileSync(out, cs);
console.log(`wrote ${path.relative(path.join(front, '..'), out)}: ${NAMES.length} icons, ${cs.length} bytes`);
