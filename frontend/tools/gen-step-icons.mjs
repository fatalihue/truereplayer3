// Writes src/shell/list/stepIcons.css: the step list's icons as CSS masks, one rule per lucide
// icon, drawn from the icon's own nodes. A step's icon is then one <span> with a data-icon
// attribute instead of an SVG tree per row — the same trade the library's glyphs make, and the
// one that matters at a thousand steps. Run after changing the list below or upgrading lucide:
//   node tools/gen-step-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const front = path.join(here, '..');
const iconsDir = path.join(front, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const out = path.join(front, 'src', 'shell', 'list', 'stepIcons.css');

// The icons the list draws: the ones stepIcon() names in src/shell/list/stepTypes.ts, and the
// row's own glyphs (StepRow.tsx: play, pause, plus, eye-off, focus, mouse-pointer-2). The insert
// row and the Add step catalog draw theirs from here too (src/shell/insert: undo-2, redo-2,
// search, chevron-right, clock).
const NAMES = [
  'app-window', 'arrow-down', 'arrow-right-from-line', 'arrow-up', 'braces', 'chevron-right', 'circle-stop',
  'clipboard-copy', 'clock', 'corner-down-left', 'eye-off', 'focus', 'git-branch', 'globe', 'hourglass',
  'iteration-cw', 'keyboard', 'mouse', 'mouse-pointer-2', 'pause', 'pipette', 'play', 'plus', 'redo-2', 'repeat-2',
  'scan-search', 'scan-text', 'search', 'shield-check', 'skip-forward', 'split', 'table-2', 'timer', 'type',
  'undo-2', 'zap',
];

const version = JSON.parse(fs.readFileSync(path.join(front, 'node_modules', 'lucide-react', 'package.json'), 'utf8')).version;
const attrs = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}='${v}'`).join(' ');

let css = `/* Generated by tools/gen-step-icons.mjs from lucide-react ${version} (ISC). Do not edit by hand. */\n`;
for (const name of NAMES) {
  const mod = await import(pathToFileURL(path.join(iconsDir, `${name}.js`)).href);
  const body = mod.__iconNode.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
  const uri = svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23').replace(/"/g, "'");
  css += `.step-icon[data-icon='${name}'] { --step-icon: url("data:image/svg+xml,${uri}"); }\n`;
}
fs.writeFileSync(out, css);
console.log(`wrote ${path.relative(front, out)}: ${NAMES.length} icons, ${css.length} bytes`);
