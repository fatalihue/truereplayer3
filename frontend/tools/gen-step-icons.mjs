// Writes src/shell/list/stepIcons.css: the step list's icons as CSS masks, one rule per lucide
// icon, drawn from the icon's own nodes. A step's icon is then one <span> with a data-icon
// attribute instead of an SVG tree per row — the same trade the library's glyphs make, and the
// one that matters at a thousand steps. Run after changing the list below or upgrading lucide:
//   node tools/gen-step-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const front = path.join(here, '..');
const iconsDir = path.join(front, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const out = path.join(front, 'src', 'shell', 'list', 'stepIcons.css');

// The icons the list draws: the ones stepIcon() names in src/shell/list/stepTypes.ts, and the
// row's own glyphs (StepRow.tsx: play, pause, plus, eye-off, focus, mouse-pointer-2). The insert
// row and the Add step catalog draw theirs from here too (src/shell/insert: undo-2, redo-2,
// search, chevron-right, clock), and so does the Inspector (src/shell/inspector: x, layers,
// crosshair, clipboard-paste).
const NAMES = [
  'app-window', 'arrow-down', 'arrow-right-from-line', 'arrow-up', 'braces', 'chevron-right', 'circle-stop',
  'clipboard-copy', 'clipboard-paste', 'clock', 'corner-down-left', 'crosshair', 'eye-off', 'focus', 'git-branch',
  'globe', 'hourglass', 'iteration-cw', 'keyboard', 'layers', 'mouse', 'mouse-pointer-2', 'pause', 'pipette', 'play',
  'plus', 'redo-2', 'repeat-2', 'scan-search', 'scan-text', 'search', 'shield-check', 'skip-forward', 'split',
  'table-2', 'timer', 'type', 'undo-2', 'x', 'zap',
];

// The ones only the step editors draw (the checks of an If, the probes' tools, Activate Window's
// Browse… and Read from window, Run Macro's Open macro, the header's Expand and Collapse editor,
// the reference image's crop), which load with the editors and not with the app:
// src/shell/inspector/editorIcons.css.
const EDITOR_NAMES = [
  'check', 'chevron-down', 'clipboard', 'cpu', 'crop', 'dices', 'file-check', 'folder-open', 'frame', 'image', 'list',
  'maximize-2', 'minimize-2', 'refresh-cw', 'square-arrow-out-up-right', 'square-dashed', 'variable',
];
const editorOut = path.join(front, 'src', 'shell', 'inspector', 'editorIcons.css');
// …and the ones only the expanded Send Text draws (the snippets' tools, Transform…, the delivery's
// formatting warning), which load with it.
const TEXT_NAMES = ['bookmark-plus', 'download', 'pencil', 'trash-2', 'triangle-alert', 'upload', 'wand-sparkles'];
const textOut = path.join(front, 'src', 'shell', 'inspector', 'textIcons.css');
// …and the ones the dock's panel draws (a run step's state), which load with that panel.
const DOCK_NAMES = ['circle-check', 'circle-dashed', 'circle-minus', 'circle-x', 'triangle-alert'];
const dockOut = path.join(front, 'src', 'shell', 'dock', 'dockIcons.css');
// …and the Data Loop tab's (its table, its tools, its settings), which load with that tab. Some are
// also another chunk's: each chunk carries the ones it draws.
const DATA_NAMES = ['check', 'chevron-down', 'chevron-up', 'copy', 'ellipsis', 'sliders-horizontal', 'trash-2', 'triangle-alert'];
const dataOut = path.join(front, 'src', 'shell', 'data', 'dataIcons.css');

const version = JSON.parse(fs.readFileSync(path.join(front, 'node_modules', 'lucide-react', 'package.json'), 'utf8')).version;
const attrs = (o) => Object.entries(o).filter(([k]) => k !== 'key').map(([k, v]) => `${k}='${v}'`).join(' ');

async function write(names, file) {
  let css = `/* Generated by tools/gen-step-icons.mjs from lucide-react ${version} (ISC). Do not edit by hand. */\n`;
  for (const name of names) {
    const mod = await import(pathToFileURL(path.join(iconsDir, `${name}.js`)).href);
    const body = mod.__iconNode.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
    const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' stroke-linecap='round' stroke-linejoin='round'>${body}</svg>`;
    const uri = svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23').replace(/"/g, "'");
    css += `.step-icon[data-icon='${name}'] { --step-icon: url("data:image/svg+xml,${uri}"); }\n`;
  }
  fs.writeFileSync(file, css);
  console.log(`wrote ${path.relative(front, file)}: ${names.length} icons, ${css.length} bytes`);
}
await write(NAMES, out);
await write(EDITOR_NAMES, editorOut);
await write(TEXT_NAMES, textOut);
await write(DOCK_NAMES, dockOut);
await write(DATA_NAMES, dataOut);
