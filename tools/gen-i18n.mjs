// Checks the text catalog (i18n/) and writes what is generated from it (plan
// .claude/planos/idiomas-tr3-2026-11-02.md, §3.2 and §3.5):
//   frontend/src/i18n.g.ts — every key and the blanks it takes, for the types of t() and tn();
//   Source/Strings.g.cs    — the engine's texts (the engine-* areas), both languages, as code, so the
//                            engine reads no file at launch and a missing key does not compile.
// The checks are the ones the types cannot make: the same blanks and tokens in both languages, zero in
// every pt-BR plural, the cited labels, the glossary and the terminology.
//
// Writes only what changed: a clean tree is the normal state, and `npm run build` runs this first.
//   node tools/gen-i18n.mjs           check and write
//   node tools/gen-i18n.mjs --check   check and write nothing; exit 1 when a generated file is stale
import fs from 'node:fs';
import path from 'node:path';
import {
  RAIZ, DIR, achatar, conferirForma, conferirTermos, formasDe, lacunasDe, lerIdioma, lerTs, resolverReferencias,
} from './i18n-lib.mjs';

const soConferir = process.argv.includes('--check');
const erros = [];

const areasEn = await lerIdioma('en-US');
const areasPt = await lerIdioma('pt-BR');
for (const a of Object.keys(areasEn)) if (!(a in areasPt)) erros.push(`i18n/pt-BR/${a}.ts: falta (existe em en-US)`);
for (const a of Object.keys(areasPt)) if (!(a in areasEn)) erros.push(`i18n/pt-BR/${a}.ts: não existe em en-US`);

let en, pt, grupos;
try {
  const ae = achatar(areasEn);
  grupos = ae.grupos;
  en = ae.entradas;
  pt = achatar(areasPt).entradas;
} catch (e) {
  console.error(`[i18n] ${e.message}`);
  process.exit(1);
}
erros.push(...conferirForma(en, pt));
let enR, ptR;
try { enR = resolverReferencias(en); } catch (e) { erros.push(`en-US: ${e.message}`); }
try { ptR = resolverReferencias(pt); } catch (e) { erros.push(`pt-BR: ${e.message}`); }
if (enR && ptR) {
  const glossario = await lerTs(path.join(DIR, 'glossario.ts'));
  const { TERMINOLOGIA } = await lerTs(path.join(DIR, 'terminologia.ts'));
  for (const chave of Object.keys(glossario.ISENCOES)) if (!en.has(chave)) erros.push(`ISENCOES: a chave ${chave} não existe`);
  erros.push(...conferirTermos(enR, ptR, glossario, TERMINOLOGIA));
}
if (erros.length) {
  console.error(`[i18n] o catálogo tem ${erros.length} problema(s):\n  ${erros.join('\n  ')}`);
  process.exit(1);
}

// ── frontend/src/i18n.g.ts
const tipoLacunas = (e) => {
  const nomes = lacunasDe(e);
  if (e.tipo === 'plural' && !nomes.includes('count')) nomes.push('count');
  if (!nomes.length) return 'never';
  return `{ ${nomes.sort().map((n) => `${n}: ${n === 'count' ? 'number' : 'string | number'}`).join('; ')} }`;
};
const linhasChaves = [...en].filter(([k]) => !k.startsWith('engine-')).map(([k, e]) => `  '${k}': ${tipoLacunas(e)};`);
const linhasTabelas = [...grupos]
  .filter(([k, g]) => !k.startsWith('engine-') && g.soTextos && g.textos.length && g.textos.every((t) => !lacunasDe(en.get(`${k}.${t}`)).length))
  .map(([k, g]) => `  '${k}': ${g.textos.map((t) => `'${t}'`).join(' | ')};`);
const tipos = `// GENERATED by tools/gen-i18n.mjs from i18n/en-US — do not edit (npm run i18n writes it, and the
// build checks it). The keys of the catalog and the blanks each one takes; i18n.ts types t() and tn()
// with it.

/** Each key and its blanks: never takes none; count picks the form of a plural. */
export type Chaves = {
${linhasChaves.join('\n')}
};

/** The groups of plain texts, without blanks, that tn() gives as an object. */
export type Tabelas = {
${linhasTabelas.join('\n')}
};
`;

// ── Source/Strings.g.cs: the engine-* areas. Area engine-tray, key exit → S.TrayExit.
const pascal = (s) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const csEsc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n');
// A text with blanks is an interpolated string: its own braces (the tokens) double, the blanks become holes.
const csTexto = (texto) => {
  const ms = [...texto.matchAll(/\{\{\s*([A-Za-z_]\w*)\s*\}\}/g)];
  if (!ms.length) return `"${csEsc(texto)}"`;
  const fixo = (s) => csEsc(s).replace(/[{}]/g, (c) => c + c);
  let out = '';
  let pos = 0;
  for (const m of ms) {
    out += fixo(texto.slice(pos, m.index)) + `{${m[1]}}`;
    pos = m.index + m[0].length;
  }
  return `$"${out}${fixo(texto.slice(pos))}"`;
};
const csForma = (idioma, e) => {
  if (e.tipo === 'texto') return csTexto(e.texto);
  const f = e.formas;
  const um = idioma === 'pt-BR' ? 'count < 2' : 'count == 1';
  const resto = f.one === f.other ? csTexto(f.other) : `(${um} ? ${csTexto(f.one)} : ${csTexto(f.other)})`;
  return 'zero' in f ? `(count == 0 ? ${csTexto(f.zero)} : ${resto})` : resto;
};
const membros = [];
for (const [chave, e] of enR) {
  if (!chave.startsWith('engine-')) continue;
  const [area, ...resto] = chave.split('.');
  const nome = pascal(area.slice('engine-'.length)) + pascal(resto.join('.'));
  const nomes = lacunasDe(e);
  if (e.tipo === 'plural' && !nomes.includes('count')) nomes.push('count');
  const params = nomes.map((n) => `${n === 'count' ? 'int' : 'string'} ${n}`).join(', ');
  // One line of XML doc: a text with a line break would end the comment and turn the rest into code.
  const doc = formasDe(e)[0].replace(/[<>&]/g, ' ').replace(/\r?\n/g, ' ');
  const corpo = `IsPt ? ${csForma('pt-BR', ptR.get(chave))} : ${csForma('en-US', e)}`;
  membros.push(`        /// <summary>${chave} · ${doc}</summary>`);
  membros.push(nomes.length ? `        public static string ${nome}(${params}) => ${corpo};` : `        public static string ${nome} => ${corpo};`);
}
const cs = `// <auto-generated>
// GENERATED by tools/gen-i18n.mjs from i18n/*/engine-*.ts — do not edit (npm run i18n in frontend
// writes it, and the build checks it). Each text in both languages, picked by S.Language (Strings.cs).
// </auto-generated>
namespace TrueReplayer.Services
{
    public static partial class S
    {
${membros.join('\n')}
    }
}
`;

// ── Write what changed.
let velhos = 0;
for (const [arquivo, conteudo] of [[path.join(RAIZ, 'frontend', 'src', 'i18n.g.ts'), tipos], [path.join(RAIZ, 'Source', 'Strings.g.cs'), cs]]) {
  const atual = fs.existsSync(arquivo) ? fs.readFileSync(arquivo, 'utf8').replace(/\r\n/g, '\n') : null;
  if (atual === conteudo) continue;
  velhos++;
  if (soConferir) console.error(`[i18n] ${path.relative(RAIZ, arquivo)} está velho: rode npm run i18n`);
  else { fs.writeFileSync(arquivo, conteudo); console.log(`[i18n] escreveu ${path.relative(RAIZ, arquivo)}`); }
}
if (soConferir && velhos) process.exit(1);
console.log(`[i18n] ok: ${en.size} chaves, ${Object.keys(areasEn).length} áreas`);
